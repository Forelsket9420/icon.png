// Sub-Store 合并脚本：先去掉 27 个国家，再把剩下的按字母（拼音）排序
// 用法：订阅编辑 > 节点操作 > 脚本操作，粘贴整个 operator 函数
// 效果：172 个节点 -> 去掉 27 国 -> 剩下 68 个按下面字母顺序排

async function operator(proxies = [], targetPlatform, context) {
  // 1. 要去掉的 27 个国家/地区
  const remove = ['美国', '香港', '日本', '新加坡', '英国', '德国', '加拿大', '台湾', '马来西亚', '菲律宾', '阿根廷', '澳大利亚', '巴林', '捷克', '厄瓜多尔', '埃塞俄比亚', '法国', '韩国', '哈萨克', '蒙古', '澳门', '墨西哥', '新西兰', '泰国', '土耳其', '乌拉圭', '越南'];

  // 2. 剩下国家的字母（拼音）顺序
  const order = ['阿尔及利亚', '阿塞拜疆', '埃及', '爱尔兰', '爱沙尼亚', '安哥拉', '奧地利', '巴基斯坦', '巴西', '保加利亚', '北马其顿', '比利时', '冰岛', '波兰', '玻利维亚', '朝鲜', '丹麦', '迪拜', '俄罗斯', '法属圭亚那', '芬兰', '哥伦比亚', '格陵兰岛', '荷兰', '洪都拉斯', '柬埔寨', '卡塔尔', '克罗地亚', '肯尼亚', '拉脫维亚', '老挝', '立陶宛', '卢森堡', '罗马尼亚', '马耳他', '孟加拉国', '秘鲁', '缅甸', '摩尔多瓦', '南非', '南极洲', '尼泊尔', '尼日利亚', '挪威', '葡萄牙', '瑞典', '瑞士', '塞尔维亚', '沙特阿拉伯', '斯洛文尼亚', '塔吉克', '坦桑尼亚', '乌克兰', '乌茲別克', '西班牙', '希腊', '匈牙利', '亚美尼亚', '伊拉克', '以色列', '意大利', '印度', '印度尼西亚', '智利'];

  const idx = (name) => {
    const i = order.findIndex((k) => (name || '').includes(k));
    return i === -1 ? 999 : i;
  };

  return proxies
    .filter((p) => !remove.some((k) => (p.name || '').includes(k)))
    .sort((a, b) => {
      const d = idx(a.name || '') - idx(b.name || '');
      return d !== 0 ? d : (a.name || '').localeCompare(b.name || '', 'zh-CN');
    });
}
